#pragma once

#include <array>
#include <cctype>
#include <cstdint>
#include <fstream>
#include <string>

namespace ax::ui::retro {

// 5x5 bitmap glyph stored as 5 bytes (top 5 bits of each byte hold row pixels).
using Glyph5x5 = std::array<std::uint8_t, 5>;

class RetroBitmapFont {
public:
    static constexpr std::size_t kGlyphCount = 64;
    static constexpr int kGlyphWidth = 5;
    static constexpr int kGlyphHeight = 5;

    RetroBitmapFont() { ResetToDefault(); }

    void ResetToDefault() noexcept {
        glyphs_.fill({0x00, 0x00, 0x00, 0x00, 0x00});

        // 0x00: Space
        glyphs_[0x00] = {0x00, 0x00, 0x00, 0x00, 0x00};
        // 0x01..0x0A: Digits 0..9
        glyphs_[0x01] = {0x70, 0x88, 0x98, 0xA8, 0x70}; // 0
        glyphs_[0x02] = {0x20, 0x60, 0x20, 0x20, 0x70}; // 1
        glyphs_[0x03] = {0x70, 0x88, 0x10, 0x20, 0xF8}; // 2
        glyphs_[0x04] = {0xF0, 0x10, 0x70, 0x10, 0xF0}; // 3
        glyphs_[0x05] = {0x90, 0x90, 0xF8, 0x10, 0x10}; // 4
        glyphs_[0x06] = {0xF8, 0x80, 0xF0, 0x10, 0xF0}; // 5
        glyphs_[0x07] = {0x78, 0x80, 0xF0, 0x88, 0x70}; // 6
        glyphs_[0x08] = {0xF8, 0x10, 0x20, 0x40, 0x40}; // 7
        glyphs_[0x09] = {0x70, 0x88, 0x70, 0x88, 0x70}; // 8
        glyphs_[0x0A] = {0x70, 0x88, 0x78, 0x08, 0x70}; // 9

        // 0x0B..0x24: Uppercase A..Z
        glyphs_[0x0B] = {0x70, 0x88, 0xF8, 0x88, 0x88}; // A
        glyphs_[0x0C] = {0xF0, 0x88, 0xF0, 0x88, 0xF0}; // B
        glyphs_[0x0D] = {0x78, 0x80, 0x80, 0x80, 0x78}; // C
        glyphs_[0x0E] = {0xF0, 0x88, 0x88, 0x88, 0xF0}; // D
        glyphs_[0x0F] = {0xF8, 0x80, 0xF0, 0x80, 0xF8}; // E
        glyphs_[0x10] = {0xF8, 0x80, 0xF0, 0x80, 0x80}; // F
        glyphs_[0x11] = {0x78, 0x80, 0x98, 0x88, 0x78}; // G
        glyphs_[0x12] = {0x88, 0x88, 0xF8, 0x88, 0x88}; // H
        glyphs_[0x13] = {0x70, 0x20, 0x20, 0x20, 0x70}; // I
        glyphs_[0x14] = {0x38, 0x10, 0x10, 0x90, 0x60}; // J
        glyphs_[0x15] = {0x88, 0x90, 0xE0, 0x90, 0x88}; // K
        glyphs_[0x16] = {0x80, 0x80, 0x80, 0x80, 0xF8}; // L
        glyphs_[0x17] = {0x88, 0xD8, 0xA8, 0x88, 0x88}; // M
        glyphs_[0x18] = {0x88, 0xC8, 0xA8, 0x98, 0x88}; // N
        glyphs_[0x19] = {0x70, 0x88, 0x88, 0x88, 0x70}; // O
        glyphs_[0x1A] = {0xF0, 0x88, 0xF0, 0x80, 0x80}; // P
        glyphs_[0x1B] = {0x70, 0x88, 0xA8, 0x90, 0x68}; // Q
        glyphs_[0x1C] = {0xF0, 0x88, 0xF0, 0x90, 0x88}; // R
        glyphs_[0x1D] = {0x78, 0x80, 0x70, 0x08, 0xF0}; // S
        glyphs_[0x1E] = {0xF8, 0x20, 0x20, 0x20, 0x20}; // T
        glyphs_[0x1F] = {0x88, 0x88, 0x88, 0x88, 0x70}; // U
        glyphs_[0x20] = {0x88, 0x88, 0x88, 0x50, 0x20}; // V
        glyphs_[0x21] = {0x88, 0x88, 0xA8, 0xD8, 0x88}; // W
        glyphs_[0x22] = {0x88, 0x50, 0x20, 0x50, 0x88}; // X
        glyphs_[0x23] = {0x88, 0x88, 0x70, 0x20, 0x20}; // Y
        glyphs_[0x24] = {0xF8, 0x10, 0x20, 0x40, 0xF8}; // Z

        // Punctuation & symbols
        glyphs_[0x25] = {0x00, 0x20, 0x70, 0x20, 0x00}; // +
        glyphs_[0x26] = {0x00, 0x00, 0x70, 0x00, 0x00}; // -
        glyphs_[0x27] = {0x08, 0x10, 0x20, 0x40, 0x80}; // /
        glyphs_[0x28] = {0x00, 0x70, 0x00, 0x70, 0x00}; // =
        glyphs_[0x29] = {0x00, 0x00, 0x00, 0x00, 0x20}; // .
        glyphs_[0x2A] = {0x00, 0x00, 0x00, 0x20, 0x40}; // ,
        glyphs_[0x2B] = {0x20, 0x20, 0x20, 0x00, 0x20}; // !
        glyphs_[0x2C] = {0x70, 0x08, 0x30, 0x00, 0x20}; // ?
        glyphs_[0x2D] = {0x10, 0x20, 0x40, 0x20, 0x10}; // <
        glyphs_[0x2E] = {0x00, 0x20, 0x00, 0x20, 0x00}; // :
        glyphs_[0x2F] = {0x40, 0x20, 0x10, 0x20, 0x40}; // >
        glyphs_[0x30] = {0x00, 0x00, 0xF8, 0x00, 0xF8}; // #
        glyphs_[0x31] = {0x00, 0x20, 0x20, 0x20, 0x00}; // |
    }

    std::uint8_t MapAsciiToGlyph(char ch) const noexcept {
        const unsigned char uch = static_cast<unsigned char>(ch);
        if (uch == ' ') return 0x00;
        if (uch >= '0' && uch <= '9') return static_cast<std::uint8_t>(0x01 + (uch - '0'));
        const char upper = static_cast<char>(std::toupper(uch));
        if (upper >= 'A' && upper <= 'Z') return static_cast<std::uint8_t>(0x0B + (upper - 'A'));
        switch (ch) {
            case '+': return 0x25;
            case '-': return 0x26;
            case '/': return 0x27;
            case '=': return 0x28;
            case '.': return 0x29;
            case ',': return 0x2A;
            case '!': return 0x2B;
            case '?': return 0x2C;
            case '<': return 0x2D;
            case ':': return 0x2E;
            case '>': return 0x2F;
            case '#': return 0x30;
            case '|': return 0x31;
            default:  return 0x00;
        }
    }

    bool LoadOverrideFile(const std::string& path) {
        std::ifstream in(path);
        if (!in.is_open()) return false;

        std::size_t glyph_idx = 0;
        int row_idx = 0;
        std::string line;

        while (std::getline(in, line) && glyph_idx < kGlyphCount) {
            std::string trimmed;
            for (char c : line) {
                if (c == ';' || c == '#') break;
                if (!std::isspace(static_cast<unsigned char>(c))) {
                    trimmed.push_back(c);
                }
            }
            if (trimmed.empty()) continue;
            if (trimmed == "EOF") break;

            if (trimmed.size() >= 5 &&
                (trimmed.find_first_not_of("01.#*") == std::string::npos)) {
                std::uint8_t mask = 0;
                for (int col = 0; col < 5; ++col) {
                    const char px = (col < static_cast<int>(trimmed.size())) ? trimmed[static_cast<std::size_t>(col)] : '0';
                    const bool lit = (px == '1' || px == '#' || px == '*');
                    if (lit) {
                        mask |= static_cast<std::uint8_t>(0x80u >> col);
                    }
                }
                glyphs_[glyph_idx][static_cast<std::size_t>(row_idx)] = mask;
                ++row_idx;
                if (row_idx >= kGlyphHeight) {
                    row_idx = 0;
                    ++glyph_idx;
                }
            }
        }
        return glyph_idx > 0 || row_idx > 0;
    }

    const Glyph5x5& Glyph(std::uint8_t index) const noexcept {
        return glyphs_[index % kGlyphCount];
    }

private:
    std::array<Glyph5x5, kGlyphCount> glyphs_{};
};

} // namespace ax::ui::retro
